import assert from 'node:assert/strict';
import {validProjectInput,validStageInput,projectGate,stageDeliveryStatus} from '../src/lib/projects.ts';
const id='00000000-0000-4000-8000-000000000001';
const stage={title:'运行流程',acceptance:'用户完成操作，失败可恢复',task_ids:[id],state:'pending'};
assert(validProjectInput({title:'新业务',goal:'完成产品流程',acceptance:'用户能够使用',integration:'完成输入到交付',stages:[stage],requestKey:id}));
for(const stages of [[],Array(9).fill(stage),[{...stage,acceptance:''}],null])assert(!validStageInput(stages));
assert(!validStageInput([{...stage,task_ids:['not-a-uuid']}],true));
assert(!validProjectInput({title:'x',goal:'g',acceptance:'a',integration:'i',stages:[stage],requestKey:'bad'}));
const p={id,title:'p',goal:'g',acceptance:'a',integration_acceptance:'i',stages:[stage,{...stage,title:'真实验证',task_ids:[]}],plan_id:id,revision:0,state:'active',integration_state:'pending'};
const assignments=[{id,title:'实现',input:{plan_id:id,step_index:0,dependencies:[]},result:{work_order_id:'order'}}];
const work=[{id:'order',result:{review_state:'open'}}];
assert(projectGate(p,'stage',0,assignments,work));
assert(!stageDeliveryStatus(stage,assignments,work).ready,'generated is not accepted');
work[0].result.review_state='accepted';
assert.equal(projectGate(p,'stage',0,assignments,work),'');
assert(projectGate(p,'stage',1,assignments,work),'later gate needs previous gate');
p.stages[0].state='passed';
assert.equal(projectGate(p,'stage',1,assignments,work),'');
assert(projectGate(p,'integration',null,assignments,work));
p.stages[1].state='passed';
assert.equal(projectGate(p,'integration',null,assignments,work),'');
assert(projectGate(p,'final',null,assignments,work),'business needs end-to-end verification');
p.integration_state='passed';
assert.equal(projectGate(p,'final',null,assignments,work),'');
assert(projectGate(p,'stage',0,[],work),'missing assignment fails closed');
console.log('PASS: project input boundaries, missing records, accepted task gates, sequential stages and distinct end-to-end/final gates');
